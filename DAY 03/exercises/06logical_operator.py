#logical operator (and ).
a, b = True, False
print("AND result:", a and b)  # False

#logical operator (or).
a, b = True, False
print("OR result:", a or b)   # True

#logical operator(not).
a = True
print("NOT result:", not a)   # False

#logical operator (and, or,not)
x, y, z = True, False, True
print("Combined result:", (x and not y) or (not z))  # True

